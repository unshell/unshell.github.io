    drawMap(grids) {
        const map = document.querySelector('.map'), grid = document.createElement('div'),
            gridSize = ESCAPE.grid.size;
        for (let i = 0; i < grids.length; i++) {
            for (let j = 0; j < grids[i].length; j++) {
                grid.className = 'grid';
                grid.style.top = i * gridSize + 'px';
                grid.style.left = j * gridSize + 'px';
                grid.innerHTML = ESCAPE.grid.enums[grids[i][j]] || '';
                if (!grid.innerHTML) continue;
                grid.className += ' grid-enum-' + grids[i][j];
                map.appendChild(grid.cloneNode(true));
            }
        }
    },
    isPassable(grids, top, left) {
        let y = top / ESCAPE.grid.size, x = left / ESCAPE.grid.size;
        return ![1, 7].includes(grids[y][x]);
    }
